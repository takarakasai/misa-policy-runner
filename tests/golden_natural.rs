//! Golden-vector cross-check of the trajectory + IK port against the Python
//! reference (`mit_rl/natural_walk.py`).
//!
//! The vectors were produced by torch (f32), so agreement is bounded by f32
//! resolution of intermediate values — 2e-5 absolute covers it. The two
//! implementations disagreeing is SILENT on the robot (it walks, worse), so
//! this is the check that matters for deployment.
//!
//! Regenerate with the snippet in this file's git history / go2_rl:
//!   from mit_rl.natural_walk import trajectory, ik
//!   feet, swing, height = trajectory(t, cmd, sg, yg, bh); q = ik(feet)

use misa_policy_runner::natural::{ik, trajectory, TrajectoryCfg};

struct Golden {
    t: f64,
    cmd: [f64; 3],
    stride_gain: f64,
    yaw_stride_gain: Option<f64>,
    body_height: Option<f64>,
    feet: [[f64; 3]; 4],
    swing: [bool; 4],
    height: f64,
    q_isaac: [f64; 12],
}

const TOL: f64 = 2e-5;

#[test]
fn trajectory_and_ik_match_the_python_reference() {
    for (n, g) in goldens().iter().enumerate() {
        let cfg = TrajectoryCfg {
            stride_gain: g.stride_gain,
            yaw_stride_gain: g.yaw_stride_gain,
            body_height: g.body_height,
            support_shift_gain: 1.0,
        };
        let r = trajectory(g.t, g.cmd, &cfg);
        assert_eq!(r.swing, g.swing, "case {n} (t={}) swing", g.t);
        assert!(
            (r.height - g.height).abs() < TOL,
            "case {n} height {} vs {}",
            r.height,
            g.height
        );
        for l in 0..4 {
            for k in 0..3 {
                assert!(
                    (r.feet[l][k] - g.feet[l][k]).abs() < TOL,
                    "case {n} (t={}) foot {l} axis {k}: {} vs python {}",
                    g.t,
                    r.feet[l][k],
                    g.feet[l][k]
                );
            }
        }
        // IK evaluated on the PYTHON feet, so this isolates the IK port from
        // trajectory differences.
        let q = ik(&g.feet);
        for i in 0..12 {
            assert!(
                (q[i] - g.q_isaac[i]).abs() < TOL,
                "case {n} (t={}) q[{i}]: {} vs python {}",
                g.t,
                q[i],
                g.q_isaac[i]
            );
        }
    }
}

