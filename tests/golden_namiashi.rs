//! namiashi trot_target の Python 照合（go2_rl sim2sim_namiashi_ref_mujoco.py
//! と namiashi_rl/mdp_custom._trot_target_q が正典。生成スニペットは
//! go2_rl 側の作業ログ参照）。両実装の食い違いは実機でしか現れないので、
//! ここで 1e-7 レベルで固定する。

use misa_policy_runner::namiashi::trot_target;

struct Golden {
    tau: f64,
    cmd: [f64; 3],
    q: [f64; 12],
}

#[test]
fn trot_target_matches_the_python_reference() {
    let cases = [
        Golden {
            tau: 0.0,
            cmd: [0.0, 0.0, 0.0],
            q: [0.0, 0.0, 0.0, 0.0, 0.695, 0.695, 0.695, 0.695, -1.39, -1.39, -1.39, -1.39],
        },
        Golden {
            tau: 0.33,
            cmd: [0.2, 0.0, 0.0],
            q: [
                0.001190191, 0.000416054, 0.000722324, -0.00168523,
                0.711315835, 0.830305751, 0.829946414, 0.710870785,
                -1.463566206, -1.601986451, -1.601294802, -1.466697626,
            ],
        },
        Golden {
            tau: 0.71,
            cmd: [0.1, 0.05, 0.2],
            q: [
                0.000299623, -0.000090673, 0.000047649, -0.000087397,
                0.778777101, 0.701487913, 0.702210239, 0.777876674,
                -1.485961824, -1.460678023, -1.463437462, -1.485693846,
            ],
        },
        Golden {
            tau: 1.27,
            cmd: [0.3, 0.0, 0.0],
            q: [
                0.000178576, 0.001358098, 0.00152515, -0.002161622,
                0.677158327, 0.84245919, 0.841504338, 0.675039654,
                -1.461621836, -1.539265984, -1.537376785, -1.462209585,
            ],
        },
        Golden {
            tau: 0.5,
            cmd: [0.879, 0.0, 0.0],
            q: [
                0.008223976, -0.002286133, -0.000702567, -0.004577726,
                0.863068917, 0.692381403, 0.69308458, 0.861158088,
                -1.515765143, -1.731657818, -1.733560098, -1.523008162,
            ],
        },
    ];
    for (n, g) in cases.iter().enumerate() {
        let q = trot_target(g.tau, g.cmd);
        for i in 0..12 {
            assert!(
                (q[i] - g.q[i]).abs() < 1e-7,
                "case {n} (tau={}) q[{i}]: {} vs python {}",
                g.tau,
                q[i],
                g.q[i]
            );
        }
    }
}
