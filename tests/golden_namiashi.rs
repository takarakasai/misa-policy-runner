//! namiashi trot_target（v12 解析形）の Python 照合。正典は go2_rl
//! sim2sim_namiashi_ref_mujoco.py の trot_target（namiashi_rl/mdp_custom
//! ._trot_target_q と 1e-7 で一致済み）。値は同スクリプトの numpy 実装を
//! 8 ケースで評価したもの。両実装の食い違いは実機でしか現れないので、
//! ここで 1e-7 レベルで固定する。

use misa_policy_runner::namiashi::trot_target;

struct Golden {
    tau: f64,
    cmd: [f64; 3],
    q: [f64; 12],
}

#[test]
fn trot_target_matches_the_python_reference() {
    let cases = [
        Golden {
            tau: 0.0,
            cmd: [0.0, 0.0, 0.0],
            q: [0.0, 0.0, 0.0, 0.0, 0.695, 0.695, 0.695, 0.695, -1.39, -1.39, -1.39, -1.39],
        },
        Golden {
            tau: 0.33,
            cmd: [0.2, 0.0, 0.0],
            q: [
                0.0, 0.0, 0.0, 0.0,
                0.672904616, 0.873680494, 0.873680494, 0.672904616,
                -1.38942928, -1.624209922, -1.624209922, -1.38942928,
            ],
        },
        Golden {
            tau: 0.71,
            cmd: [0.1, 0.05, 0.2],
            q: [
                -0.066451977, 0.04267147, -0.017568525, 0.027315032,
                0.735712839, 0.661050103, 0.698830225, 0.789720943,
                -1.463044456, -1.41748808, -1.40298416, -1.432142149,
            ],
        },
        Golden {
            tau: 1.27,
            cmd: [-0.12, 0.0, 0.0],
            q: [
                0.0, 0.0, 0.0, 0.0,
                0.717585543, 0.684797282, 0.684797282, 0.717585543,
                -1.389370778, -1.465664962, -1.465664962, -1.389370778,
            ],
        },
        Golden {
            tau: 0.5,
            cmd: [0.0, 0.15, 0.0],
            q: [
                -0.018457248, 0.050270831, 0.049399985, -0.018349481,
                0.701813879, 0.816553405, 0.782589116, 0.687761734,
                -1.403627758, -1.633106809, -1.565178232, -1.375523467,
            ],
        },
        Golden {
            tau: 0.83,
            cmd: [0.0, 0.0, 0.4],
            q: [
                -0.047875208, 0.019296357, -0.019296357, 0.047875208,
                0.930938577, 0.687627153, 0.716354493, 1.002676878,
                -1.933615455, -1.403981646, -1.403981646, -1.933615455,
            ],
        },
        Golden {
            tau: 0.17,
            cmd: [0.2, 0.0, 0.3],
            q: [
                0.051654033, -0.063253097, 0.063253097, -0.051654033,
                0.650949168, 0.778218447, 0.694553823, 0.569500078,
                -1.3461505, -1.317682191, -1.335031743, -1.334672224,
            ],
        },
        Golden {
            tau: 0.6,
            cmd: [0.35, -0.1, -0.4],
            q: [
                0.082892854, -0.116980662, 0.040939447, -0.028852085,
                0.780349605, 0.56346957, 0.463943383, 0.735617461,
                -1.293199598, -1.275313121, -1.311826246, -1.363217005,
            ],
        },
    ];
    for (n, g) in cases.iter().enumerate() {
        let q = trot_target(g.tau, g.cmd);
        for i in 0..12 {
            assert!(
                (q[i] - g.q[i]).abs() < 1e-7,
                "case {n} (tau={}, cmd={:?}) q[{i}]: {} vs python {}",
                g.tau,
                g.cmd,
                q[i],
                g.q[i]
            );
        }
    }
}
